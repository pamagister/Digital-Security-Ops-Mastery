#!/usr/bin/env bash
#
# Run a configured Borg Backup job. Configuration is created by
# borg_backup_init.sh. Design target: Borg 1.x.

set -Eeuo pipefail
IFS=$'\n\t'

PROGNAME="${0##*/}"
CONFIG_FILE="${BORG_BACKUP_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/borg-backup/config}"

die() { printf 'Error: %s\n' "$*" >&2; exit 1; }
info() { printf '\n==> %s\n' "$*"; }

usage() {
    cat <<EOF
Usage: $PROGNAME [--dry-run] [--no-prune] [--help]

Run the backup defined in:
  $CONFIG_FILE

Options:
  --dry-run   Show Borg create/prune operations without changing the repository.
  --no-prune  Create the archive but skip pruning and compaction.
  -h, --help  Show this help.
EOF
}

DRY_RUN=0
NO_PRUNE=0
while (($#)); do
    case "$1" in
        --dry-run) DRY_RUN=1 ;;
        --no-prune) NO_PRUNE=1 ;;
        -h|--help) usage; exit 0 ;;
        *) usage >&2; die "Unknown option: $1" ;;
    esac
    shift
done

[[ -r "$CONFIG_FILE" ]] || die "Configuration not found or unreadable: $CONFIG_FILE"
[[ "$(stat -c '%u' "$CONFIG_FILE")" == "$(id -u)" ]] || die "Configuration must be owned by the current user."
mode="$(stat -c '%a' "$CONFIG_FILE")"
(( (8#$mode & 077) == 0 )) || die "Configuration permissions are too broad. Run chmod 600 on it."

# Config is generated by the setup script with shell-escaped values.
# shellcheck source=/dev/null
source "$CONFIG_FILE"

: "${REPOSITORY_TYPE:?Missing REPOSITORY_TYPE}"
: "${BORG_REPO:?Missing BORG_REPO}"
: "${ARCHIVE_PREFIX:?Missing ARCHIVE_PREFIX}"
: "${PASSPHRASE_FILE:?Missing PASSPHRASE_FILE}"
: "${SOURCES:?Missing SOURCES}"

[[ -f "$PASSPHRASE_FILE" && -r "$PASSPHRASE_FILE" ]] || die "Passphrase file missing or unreadable: $PASSPHRASE_FILE"
[[ "$(stat -c '%u' "$PASSPHRASE_FILE")" == "$(id -u)" ]] || die "Passphrase file must be owned by the current user."
mode="$(stat -c '%a' "$PASSPHRASE_FILE")"
(( (8#$mode & 077) == 0 )) || die "Passphrase file permissions are too broad. Run chmod 600 on it."

command -v borg >/dev/null 2>&1 || die "Borg is not installed."
version="$(borg --version)"
[[ "$version" =~ ^borg[[:space:]]+1\. ]] || die "Unsupported Borg version: $version (Borg 1.x required)."
command -v flock >/dev/null 2>&1 || die "flock is required (util-linux)."

(("${#SOURCES[@]}" > 0)) || die "No source directories configured."
for source_dir in "${SOURCES[@]}"; do
    [[ "$source_dir" == /* && -d "$source_dir" && -r "$source_dir" ]] ||
        die "Source directory missing, unreadable, or not absolute: $source_dir"
done

case "$REPOSITORY_TYPE" in
    local)
        : "${MOUNTPOINT:?Missing MOUNTPOINT for local repository}"
        [[ "$MOUNTPOINT" == /* ]] || die "MOUNTPOINT must be absolute."
        mountpoint -q "$MOUNTPOINT" ||
            die "NAS mount is not active: $MOUNTPOINT. Refusing to write to the local mount-point directory."
        [[ -d "$BORG_REPO" && -w "$BORG_REPO" ]] || die "Repository missing or not writable: $BORG_REPO"
        repo_real="$(realpath "$BORG_REPO")"
        mount_real="$(realpath "$MOUNTPOINT")"
        [[ "$repo_real" == "$mount_real/"* ]] || die "Repository is no longer below the configured mount point."
        ;;
    ssh)
        [[ "$BORG_REPO" =~ ^ssh://[^/]+/.+ ]] || die "Invalid SSH repository URL in config."
        ;;
    *) die "Unknown repository type: $REPOSITORY_TYPE" ;;
esac

export BORG_PASSPHRASE_FILE="$PASSPHRASE_FILE"
# Borg executes the passcommand without a shell, so expand the path here instead
# of relying on "$BORG_PASSPHRASE_FILE" being substituted at runtime.
printf -v BORG_PASSCOMMAND 'cat -- %q' "$PASSPHRASE_FILE"
export BORG_PASSCOMMAND

lock_dir="${XDG_CACHE_HOME:-$HOME/.cache}/borg-backup"
mkdir -p "$lock_dir"
chmod 700 "$lock_dir"
exec 9>"$lock_dir/backup.lock"
flock -n 9 || die "Another Borg backup process is already running."

timestamp="$(date +%Y-%m-%dT%H%M%S)"
archive_name="$ARCHIVE_PREFIX-$timestamp"

info "Backup preflight"
printf 'Borg version : %s\nRepository   : %s\nArchive      : %s\nSources:\n' "$version" "$BORG_REPO" "$archive_name"
printf '  - %s\n' "${SOURCES[@]}"

create_args=(create --stats --show-rc --compression lz4 --exclude-caches)
if (( DRY_RUN )); then create_args+=(--dry-run --list); fi
create_args+=("$BORG_REPO::$archive_name")
create_args+=("${SOURCES[@]}")

info "Creating archive"
borg "${create_args[@]}"

if (( NO_PRUNE )); then
    info "Pruning skipped (--no-prune)."
    exit 0
fi

keep_daily="${KEEP_DAILY:-14}"
keep_weekly="${KEEP_WEEKLY:-8}"
keep_monthly="${KEEP_MONTHLY:-12}"
for value in "$keep_daily" "$keep_weekly" "$keep_monthly"; do
    [[ "$value" =~ ^[0-9]+$ ]] || die "Retention values must be non-negative integers."
done

info "Pruning only archives with prefix: $ARCHIVE_PREFIX-"
prune_args=(prune --list --show-rc --glob-archives "$ARCHIVE_PREFIX-*"
    --keep-daily="$keep_daily" --keep-weekly="$keep_weekly" --keep-monthly="$keep_monthly")
if (( DRY_RUN )); then prune_args+=(--dry-run); fi
prune_args+=("$BORG_REPO")
borg "${prune_args[@]}"

if [[ "${COMPACT_AFTER_PRUNE:-yes}" == "yes" && "$DRY_RUN" -eq 0 ]]; then
    info "Compacting repository"
    borg compact "$BORG_REPO"
fi

info "Backup completed successfully"
printf 'Repository: %s\nArchive:    %s\n' "$BORG_REPO" "$archive_name"
